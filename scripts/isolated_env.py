"""Create the env file of the Phase 12 ISOLATED test stack (compose project ``fraudstream-p12``).

    python scripts/isolated_env.py [--out .env.isolated] [--force]

Fresh random secrets (never the live ones), host ports that differ from the live stack, a dedicated network
name and dedicated login accounts (``p12admin`` / ``p12analyst``). The file is gitignored and dockerignored
(``.env.*``). Nothing is printed except key names.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from new_env import SECRET_KEYS, secret_for  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
VALUES = {
    "FRAUDSTREAM_ENV": "test",
    "FRAUDSTREAM_NETWORK": "fraudstream-p12",
    "POSTGRES_DB": "fraudstream",
    "POSTGRES_USER": "fraudstream",
    "KAFKA_HOST_PORT": "19092",
    "POSTGRES_HOST_PORT": "15433",
    "REDIS_HOST_PORT": "16380",
    "SPARK_UI_PORT": "14040",
    "FRONTEND_HOST_PORT": "18080",
    "FRONTEND_LOCAL_HOST_PORT": "18081",
    # KAFKA_CLUSTER_ID is NOT changed: a restored kafka-data volume keeps the cluster id it was created with
    # (Kafka refuses to start on a mismatch). It is an identifier, not a secret; the network is separate.
    "FRAUDSTREAM_ADMIN_USERNAME": "p12admin",
    "FRAUDSTREAM_ANALYST_USERNAME": "p12analyst",
    "ACCESS_TOKEN_MINUTES": "30",
    "REFRESH_TOKEN_DAYS": "7",
    "LOGIN_RATE_LIMIT_PER_MINUTE": "10",
    "API_RATE_LIMIT_PER_MINUTE": "1200",
    "ARTIFACTS_MOUNT_MODE": "ro",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / ".env.isolated"))
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    out = Path(a.out)
    if out.exists() and not a.force:
        print(f"{out} exists - not modified (use --force to regenerate ALL secrets)")
        return 0
    lines = ["# Phase 12 ISOLATED test stack (project fraudstream-p12). Generated by scripts/isolated_env.py.",
             "# Random secrets, NOT the live ones. Never commit or package this file."]
    lines += [f"{k}={v}" for k, v in VALUES.items()]
    lines += [f"{k}={secret_for(k)}" for k in sorted(SECRET_KEYS)]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}: keys {', '.join([*VALUES, *sorted(SECRET_KEYS)])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
